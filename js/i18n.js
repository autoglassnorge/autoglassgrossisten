let currentLang = localStorage.getItem('ag-lang') || 'no';

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('ag-lang', lang);
  document.documentElement.lang = lang;
  updateDOM();
  updateLangSwitcher();
}

function t(key) {
  const keys = key.split('.');
  let val = I18N[currentLang];
  for (const k of keys) { val = val?.[k]; if (!val) break; }
  return val || key;
}

function updateDOM() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const text = t(key);
    if (text && text !== key) el.textContent = text;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    const text = t(key);
    if (text && text !== key) el.placeholder = text;
  });
  // Update hero prefix text
  const heroPrefix = document.querySelector('.hero-prefix');
  if (heroPrefix) heroPrefix.textContent = t('hero.prefix') + ' ';
}

function updateLangSwitcher() {
  document.querySelectorAll('.lang-switcher button').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  updateDOM();
  updateLangSwitcher();
});
